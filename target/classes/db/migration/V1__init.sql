-- V1: Initial schema

CREATE TABLE drugs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generic_name VARCHAR(255) NOT NULL UNIQUE,
    brand_names  VARCHAR(1000),
    drug_class   VARCHAR(255),
    description  TEXT
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    api_call_count BIGINT DEFAULT 0,
    created_at    TIMESTAMP
);

CREATE TABLE drug_interactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drug1_id         BIGINT NOT NULL REFERENCES drugs(id),
    drug2_id         BIGINT NOT NULL REFERENCES drugs(id),
    severity_level   VARCHAR(20) NOT NULL,
    interaction_type VARCHAR(30) NOT NULL,
    mechanism        TEXT,
    clinical_effect  TEXT,
    recommendation   TEXT,
    evidence_level   VARCHAR(20) NOT NULL
);

CREATE INDEX idx_drug_interactions_drug1 ON drug_interactions(drug1_id);
CREATE INDEX idx_drug_interactions_drug2 ON drug_interactions(drug2_id);
CREATE INDEX idx_drug_interactions_severity ON drug_interactions(severity_level);
CREATE INDEX idx_drugs_generic_name ON drugs(generic_name);
